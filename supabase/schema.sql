-- Esquema inicial de Clases IA
-- Ejecutar en Supabase → SQL Editor → New query → Run

CREATE TABLE IF NOT EXISTS public.coaches (
  codigo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombres TEXT NOT NULL,
  apellidos TEXT NOT NULL,
  correo TEXT,
  telefono TEXT,
  profesion TEXT,
  estado BOOLEAN NOT NULL DEFAULT TRUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.talleres (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  descripcion TEXT,
  duracion_horas INTEGER,
  estado BOOLEAN NOT NULL DEFAULT TRUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.coach_talleres (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  coach_id INTEGER NOT NULL REFERENCES public.coaches(codigo) ON DELETE CASCADE,
  taller_id INTEGER NOT NULL REFERENCES public.talleres(id) ON DELETE CASCADE,
  asignado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (coach_id, taller_id)
);

CREATE INDEX IF NOT EXISTS coaches_estado_idx ON public.coaches (estado);
CREATE INDEX IF NOT EXISTS talleres_estado_idx ON public.talleres (estado);
CREATE INDEX IF NOT EXISTS coach_talleres_coach_idx ON public.coach_talleres (coach_id);
CREATE INDEX IF NOT EXISTS coach_talleres_taller_idx ON public.coach_talleres (taller_id);

CREATE OR REPLACE FUNCTION public.set_actualizado_en()
RETURNS TRIGGER AS $$
BEGIN
  NEW.actualizado_en = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS coaches_set_actualizado_en ON public.coaches;
CREATE TRIGGER coaches_set_actualizado_en
BEFORE UPDATE ON public.coaches
FOR EACH ROW EXECUTE FUNCTION public.set_actualizado_en();

COMMENT ON TABLE public.coaches IS 'Mantenimiento de coaches. No se eliminan filas: se desactivan con estado = false.';
COMMENT ON TABLE public.talleres IS 'Catalogo de talleres/cursos que pueden dictar los coaches.';
COMMENT ON TABLE public.coach_talleres IS 'Relacion muchos a muchos entre coaches y talleres.';
