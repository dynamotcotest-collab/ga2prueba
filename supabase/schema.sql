-- Esquema inicial de Clases IA
-- Ejecutar en Supabase → SQL Editor → New query → Run

CREATE TABLE IF NOT EXISTS public.coaches (
  codigo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombres TEXT NOT NULL,
  apellidos TEXT NOT NULL,
  correo TEXT,
  telefono TEXT,
  profesion TEXT,
  estado BOOLEAN NOT NULL DEFAULT TRUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.sesiones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario TEXT NOT NULL,
  fin TIMESTAMPTZ NOT NULL DEFAULT now(),
  user_agent TEXT
);

CREATE INDEX IF NOT EXISTS coaches_estado_idx ON public.coaches (estado);

CREATE OR REPLACE FUNCTION public.set_actualizado_en()
RETURNS TRIGGER AS $$
BEGIN
  NEW.actualizado_en = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS coaches_set_actualizado_en ON public.coaches;
CREATE TRIGGER coaches_set_actualizado_en
BEFORE UPDATE ON public.coaches
FOR EACH ROW EXECUTE FUNCTION public.set_actualizado_en();

COMMENT ON TABLE public.coaches IS 'Mantenimiento de coaches. No se eliminan filas: se desactivan con estado = false.';
COMMENT ON TABLE public.sesiones IS 'Registro del fin de sesión al hacer logout.';
